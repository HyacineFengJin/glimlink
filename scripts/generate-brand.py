"""Export Glimlink's original SVG to application and session-bridge assets.

Authoring tool only; requires librsvg's rsvg-convert, never runs in Runtime.
The frontend SVG is the single editable source. No font or downloaded art.
"""
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent
source = root / 'operator-desktop/frontend/glimlink.svg'
mark = source.read_text()
body = mark.split('>', 1)[1].rsplit('</svg>', 1)[0]
icon = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 80 80" fill="none">\n'
    '  <!-- SPDX-License-Identifier: MIT; generated by scripts/generate-brand.py -->\n'
    '  <rect width="80" height="80" rx="21" fill="#663BDD"/>\n'
    '  <g transform="translate(8 8)">'
    + body.replace('#663BDD', '#FFFFFF')
    + '  </g>\n</svg>\n'
)
icons = root / 'operator-desktop/icons'
extension = root / 'crates/runtime-operator/src/browser_login/extension'
(icons / 'icon.svg').write_text(icon)
(extension / 'probe.svg').write_text(mark)
for path, size in [(icons / 'icon.png', 512)] + [
    (extension / f'icon-{size}.png', size) for size in (16, 32, 128)
]:
    subprocess.run(
        ['rsvg-convert', '--width', str(size), '--height', str(size),
         '--output', str(path)], input=icon.encode(), check=True,
    )
    print(path.relative_to(root))
